// Builds the exported report. Output is Markdown or a standalone, printable HTML page.
import { SEVERITIES, SEV_LABEL, sortFindings } from './analyze.js';

const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

function summary(findings) {
  const c = {};
  SEVERITIES.forEach((s) => { c[s] = findings.filter((f) => f.severity === s).length; });
  return c;
}

export function toMarkdown(meta, findings) {
  const list = sortFindings(findings);
  const c = summary(list);
  const L = [];
  L.push('# ' + (meta.project || 'Security findings'));
  L.push('');
  if (meta.tester) L.push('**Prepared by:** ' + meta.tester + '  ');
  L.push('**Date:** ' + new Date().toISOString().slice(0, 10) + '  ');
  if (meta.scope) L.push('**Scope:** ' + meta.scope + '  ');
  L.push('**Tool:** DevSec Toolkit (passive checks)');
  L.push('');
  L.push('## Summary');
  L.push('');
  L.push('| Severity | Count |');
  L.push('|---|---|');
  SEVERITIES.forEach((s) => L.push('| ' + SEV_LABEL[s] + ' | ' + c[s] + ' |'));
  L.push('');
  L.push('## Findings');
  list.forEach((f, i) => {
    L.push('');
    L.push('### ' + (i + 1) + '. ' + f.title);
    L.push('');
    L.push('- **Severity:** ' + SEV_LABEL[f.severity]);
    L.push('- **Category:** ' + f.category);
    if (f.url) L.push('- **Affected URL:** ' + f.url);
    L.push('');
    L.push(f.detail);
    if (f.evidence) { L.push(''); L.push('**Evidence**'); L.push(''); L.push('```'); L.push(f.evidence); L.push('```'); }
    L.push('');
    L.push('**Recommended fix:** ' + f.fix);
  });
  L.push('');
  L.push('---');
  L.push('*Automated, passive checks. Review each finding manually before reporting it as confirmed.*');
  return L.join('\n');
}

export function toHtml(meta, findings) {
  const list = sortFindings(findings);
  const c = summary(list);
  const color = { critical: '#8f1d14', high: '#b54708', medium: '#8a6100', low: '#1d4ed8', info: '#475467' };
  const rows = list.map((f, i) => `
  <section class="f">
    <h3>${i + 1}. ${esc(f.title)} <span class="b" style="background:${color[f.severity]}">${SEV_LABEL[f.severity]}</span></h3>
    <p class="m">${esc(f.category)}${f.url ? ' · ' + esc(f.url) : ''}</p>
    <p>${esc(f.detail)}</p>
    ${f.evidence ? '<pre>' + esc(f.evidence) + '</pre>' : ''}
    <p><strong>Recommended fix:</strong> ${esc(f.fix)}</p>
  </section>`).join('\n');
  return `<!doctype html><html lang="en"><head><meta charset="utf-8"><title>${esc(meta.project || 'Security findings')}</title>
<style>body{font:15px/1.55 system-ui,Segoe UI,sans-serif;max-width:780px;margin:32px auto;padding:0 20px;color:#14213a}
h1{margin-bottom:4px}.m{color:#667085;margin:2px 0 8px;font-size:13px}.b{color:#fff;font-size:12px;padding:2px 8px;border-radius:99px;vertical-align:middle;margin-left:6px}
table{border-collapse:collapse}td,th{border:1px solid #d9dfe7;padding:6px 14px;text-align:left}pre{background:#f1f4f8;padding:10px;border-radius:6px;white-space:pre-wrap;word-break:break-all;font-size:12.5px}
.f{border-top:1px solid #d9dfe7;padding-top:8px;margin-top:18px;break-inside:avoid}footer{margin-top:30px;color:#667085;font-size:13px}</style></head><body>
<h1>${esc(meta.project || 'Security findings')}</h1>
<p class="m">${meta.tester ? 'Prepared by ' + esc(meta.tester) + ' · ' : ''}${new Date().toISOString().slice(0, 10)}${meta.scope ? ' · Scope: ' + esc(meta.scope) : ''}</p>
<h2>Summary</h2>
<table><tr><th>Severity</th><th>Count</th></tr>${SEVERITIES.map((s) => `<tr><td>${SEV_LABEL[s]}</td><td>${c[s]}</td></tr>`).join('')}</table>
<h2>Findings</h2>${rows}
<footer>Generated by DevSec Toolkit using automated, passive checks. Review each finding manually before reporting it as confirmed.</footer>
</body></html>`;
}
